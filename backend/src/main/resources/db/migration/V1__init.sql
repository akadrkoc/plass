-- Initial schema for the Plass ticket booking system.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE venues (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    city          VARCHAR(60)  NOT NULL,
    address       VARCHAR(255) NOT NULL,
    seat_rows     INTEGER      NOT NULL CHECK (seat_rows BETWEEN 1 AND 26),
    seats_per_row INTEGER      NOT NULL CHECK (seats_per_row BETWEEN 1 AND 40),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(150)  NOT NULL,
    description    VARCHAR(4000) NOT NULL,
    category       VARCHAR(20)   NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    venue_id       BIGINT        NOT NULL REFERENCES venues (id),
    starts_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    vip_price      NUMERIC(10, 2) NOT NULL CHECK (vip_price > 0),
    premium_price  NUMERIC(10, 2) NOT NULL CHECK (premium_price > 0),
    standard_price NUMERIC(10, 2) NOT NULL CHECK (standard_price > 0),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_events_status_starts_at ON events (status, starts_at);

-- One row per physical seat of an event. "version" powers optimistic locking:
-- two concurrent requests can never both move the same seat out of AVAILABLE.
CREATE TABLE seats (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT      NOT NULL REFERENCES events (id),
    row_label   VARCHAR(3)  NOT NULL,
    seat_number INTEGER     NOT NULL,
    tier        VARCHAR(20) NOT NULL,
    status      VARCHAR(20) NOT NULL,
    version     BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_seats_event_row_number UNIQUE (event_id, row_label, seat_number)
);

CREATE INDEX idx_seats_event_status ON seats (event_id, status);

CREATE TABLE bookings (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference         VARCHAR(12)    NOT NULL,
    user_id           BIGINT         NOT NULL REFERENCES users (id),
    event_id          BIGINT         NOT NULL REFERENCES events (id),
    status            VARCHAR(20)    NOT NULL,
    total_amount      NUMERIC(10, 2) NOT NULL,
    payment_reference VARCHAR(64),
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    confirmed_at      TIMESTAMP WITH TIME ZONE,
    cancelled_at      TIMESTAMP WITH TIME ZONE,
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_bookings_reference UNIQUE (reference)
);

CREATE INDEX idx_bookings_user ON bookings (user_id, created_at DESC);
CREATE INDEX idx_bookings_status_expires ON bookings (status, expires_at);
CREATE INDEX idx_bookings_event_status ON bookings (event_id, status);

-- Seats and prices are copied into booking items so a booking keeps its
-- history even after its seats are released or prices change.
CREATE TABLE booking_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT         NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
    seat_id    BIGINT         NOT NULL REFERENCES seats (id),
    price      NUMERIC(10, 2) NOT NULL
);

CREATE INDEX idx_booking_items_booking ON booking_items (booking_id);
